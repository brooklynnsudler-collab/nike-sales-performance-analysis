LIMIT 10;

-- Business Questions
--1. How many records belong to each Product_Line?
SELECT 
	Product_Line, 
	COUNT(*) AS Total_Records
FROM nike_sales
GROUP BY Product_Line;

--2. What is the total revenue generated by each Sales_Channel?
SELECT 
		Sales_Channel, 
		SUM(Revenue) AS Total_Revenue
FROM nike_sales
GROUP BY Sales_Channel;

-- 3. What is the average profit for each Gender_Category?
SELECT 
		Gender_Category, 
		AVG(Profit) AS Average_Profit
FROM nike_sales
GROUP BY Gender_Category;

--4. Which product line generates the highest total revenue?
SELECT 
		Product_Line,
		SUM(Revenue) AS Total_Revenue
FROM nike_sales
GROUP BY Product_Line
ORDER BY Total_Revenue DESC;

--5. Which product lines have more than 400 records?
SELECT 
		Product_Line,
		COUNT(*) AS Total_Records
FROM nike_sales
GROUP BY Product_Line
HAVING COUNT(*) > 400;

--6. Which gender categories have an average profit greater than $1,300?
SELECT
		Gender_Category,
		AVG(Profit) AS Average_Profit
FROM nike_sales
GROUP BY Gender_Category
HAVING AVG(Profit) > 1300;

--7. Which product lines generate more than $50,000 in revenue from Online sales?
SELECT 
		Product_Line,
		SUM(Revenue) AS Total_Revenue
FROM nike_sales
WHERE Sales_Channel = 'Online'
GROUP BY Product_Line
HAVING SUM(Revenue) > 50000;

--8. Which regions generate more than $100,000 in total revenue?
SELECT
		Region,
		SUM(Revenue) AS Total_Revenue,
		AVG(Profit) AS Average_Profit
FROM nike_sales
GROUP BY Region
HAVING SUM(Revenue) > 100000
ORDER BY SUM(Revenue) DESC; 

--9. Which product lines have an average profit greater than $1,400?
SELECT
		Product_Line,
		AVG(Profit) AS Average_Profit,
		SUM(Revenue) AS Total_Revenue
FROM nike_sales
GROUP BY Product_Line
HAVING AVG(Profit) > 1400
ORDER BY SUM(Revenue) DESC;

--10. What is the total revenue and average profit for each sales channel?
SELECT 
		Sales_Channel,
		SUM(Revenue) AS Total_Revenue,
		AVG(Profit) AS Average_Profit
FROM nike_sales
GROUP BY Sales_Channel;

-- Classify products based on their Profit
SELECT
		Product_Name,
		Profit,
		
		CASE
				WHEN Profit >= 2000 THEN 'High Profit'
				WHEN Profit >=1000 THEN 'Medium Profit'
				ELSE 'Low Profit'
		END AS Profit_Category

FROM nike_sales;

-- How many records belong to each profit category, and what is the average profit for each category?
SELECT
		CASE
				WHEN Profit >= 2000 THEN 'High Profit'
				WHEN Profit >= 1000 THEN 'Medium Profit'
				ELSE 'Low Profit'
		END AS Profit_Category,
		
		COUNT(*) AS Record_Count,
		
		AVG(Profit) AS Average_Profit
		
FROM nike_sales
GROUP BY Profit_Category
ORDER BY Record_Count DESC;

		



